rem ====================================================================
rem Antigravity CLI Process-Scoped Proxy Wrapper
rem Generated by Install-AgyProxyPatch.ps1
rem ====================================================================
setlocal

set "HTTP_PROXY=$ProxyUrl"
set "HTTPS_PROXY=$ProxyUrl"
set "http_proxy=$ProxyUrl"
set "https_proxy=$ProxyUrl"
set "ALL_PROXY=$ProxyUrl"
set "all_proxy=$ProxyUrl"
set "NO_PROXY=localhost,127.0.0.1,::1,*.local"
rem Suppress the background updater only for this process tree.
rem To re-enable it temporarily, set AGY_CLI_DISABLE_AUTO_UPDATE=false before launch.
if not defined AGY_CLI_DISABLE_AUTO_UPDATE set "AGY_CLI_DISABLE_AUTO_UPDATE=true"

if exist "%~dp0agy-real.exe" (
    "%~dp0agy-real.exe" %*
) else if exist "%~dp0agy.exe" (
    "%~dp0agy.exe" %*
) else (
    echo [Antigravity CLI Proxy Error] Native agy.exe or agy-real.exe not found! 1>&2
    exit /b 1
)

set "EXITCODE=%ERRORLEVEL%"
endlocal & exit /b %EXITCODE%

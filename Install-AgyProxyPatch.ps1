<#
.SYNOPSIS
    Antigravity CLI (agy) 本地代理修复与局部注入维护脚本
.DESCRIPTION
    将 antigravity-local-proxy-repair 的核心防御性工程思想迁移至 Antigravity CLI。
    实现：
    1. settings.json (proxyServerURL) 的安全注入与时间戳备份。
    2. 生成进程级隔离启动器 (agy-proxy.cmd / agy-proxy.ps1)，注入大/小写全覆盖代理环境变量。
    3. 支持 PowerShell Profile 钩子注入，直接执行 agy 命令即可自动启用代理。
    4. 支持 -TakeoverAgy 二进制接管模式（将 agy.exe 备份更名为 agy-real.exe，部署 agy.cmd），实现在所有终端（CMD/PowerShell/Git Bash 等）中直接调用 agy 均自动生效。
    5. 自动优化认证模式：若未指定独立 API Key，自动移除 modelProvider 以支持使用个人 Google 账号登录。
    6. 零系统污染：不修改 Windows 全局注册表或用户环境变量。
    7. 支持 -Check 探针模式、-Uninstall 卸载模式及代理端口连通性检查。
    8. 默认只为 CLI 子进程暂停后台自动更新检查，规避部分版本的 Windows 闪黑框；外部环境变量可覆盖。
#>

[CmdletBinding()]
param(
    [ValidatePattern('^https?://')]
    [string]$ProxyUrl = 'http://127.0.0.1:7890',

    [string]$AgyBinDirectory = (Join-Path $env:LOCALAPPDATA 'agy\bin'),

    [string]$ConfigPath = (Join-Path $env:USERPROFILE '.gemini\antigravity-cli\settings.json'),

    [switch]$TakeoverAgy,

    [switch]$NoProfileHook,

    [switch]$Check,

    [switch]$Uninstall,

    [switch]$NoShim
)

$ErrorActionPreference = 'Stop'

function Write-Status([string]$Message) {
    Write-Host "[Antigravity CLI Proxy] $Message"
}

function Write-WarnStatus([string]$Message) {
    Write-Host "[Antigravity CLI Proxy][警告] $Message" -ForegroundColor Yellow
}

function Add-OrReplaceProperty($Object, [string]$Name, $Value) {
    $property = $Object.PSObject.Properties[$Name]
    if ($null -eq $property) {
        $Object | Add-Member -NotePropertyName $Name -NotePropertyValue $Value
    } else {
        $property.Value = $Value
    }
}

function Remove-PropertyIfExists($Object, [string]$Name) {
    $property = $Object.PSObject.Properties[$Name]
    if ($null -ne $property) {
        $Object.PSObject.Properties.Remove($Name)
    }
}

function Backup-File([string]$Path) {
    if (Test-Path -LiteralPath $Path) {
        $timestamp = Get-Date -Format 'yyyyMMdd-HHmmss'
        $backupPath = "$Path.bak-proxy-$timestamp"
        Copy-Item -LiteralPath $Path -Destination $backupPath -ErrorAction Stop
        Write-Status "已创建备份：$backupPath"
    }
}

function Write-Utf8NoBom([string]$Path, [string]$Content) {
    $parent = Split-Path -Parent $Path
    if (-not (Test-Path -LiteralPath $parent)) {
        New-Item -ItemType Directory -Path $parent -Force | Out-Null
    }
    [System.IO.File]::WriteAllText($Path, $Content, [System.Text.UTF8Encoding]::new($false))
}

# A private journal of the configuration values that existed before the FIRST managed install.
# Never overwrite the original snapshot during subsequent installs.
function Save-InstallState([string]$Path, $State) {
    $parent = Split-Path -Parent $Path
    if (-not (Test-Path -LiteralPath $parent)) {
        New-Item -ItemType Directory -Path $parent -Force | Out-Null
    }
    $temporary = "$Path.tmp-$([guid]::NewGuid().ToString('N'))"
    try {
        Write-Utf8NoBom $temporary (($State | ConvertTo-Json -Depth 30) + [Environment]::NewLine)
        Move-Item -LiteralPath $temporary -Destination $Path -Force -ErrorAction Stop
    } finally {
        if (Test-Path -LiteralPath $temporary) {
            Remove-Item -LiteralPath $temporary -Force
        }
    }
}

function Test-ManagedWrapper([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $false }
    return [System.IO.File]::ReadAllText($Path).Contains('Generated by Install-AgyProxyPatch.ps1')
}

function Test-PortListening([string]$HostAddress, [int]$Port) {
    try {
        $tcpClient = [System.Net.Sockets.TcpClient]::new()
        $asyncResult = $tcpClient.BeginConnect($HostAddress, $Port, $null, $null)
        $success = $asyncResult.AsyncWaitHandle.WaitOne(600, $false)
        if ($success -and $tcpClient.Connected) {
            $tcpClient.EndConnect($asyncResult)
            $tcpClient.Close()
            return $true
        }
        $tcpClient.Close()
        return $false
    } catch {
        return $false
    }
}

function Test-ProxyReachability([string]$Url) {
    try {
        $uri = [System.Uri]$Url
        return Test-PortListening $uri.Host $uri.Port
    } catch {
        return $false
    }
}

function Detect-ActiveProxyPort {
    $candidatePorts = @(7890, 7897, 33210, 10809, 10808)
    foreach ($p in $candidatePorts) {
        if (Test-PortListening '127.0.0.1' $p) {
            return "http://127.0.0.1:$p"
        }
    }
    return $null
}

function Get-RelevantProfilePaths {
    $paths = [System.Collections.Generic.List[string]]::new()
    if ($PROFILE) {
        if ($PROFILE.CurrentUserAllHosts) { $paths.Add($PROFILE.CurrentUserAllHosts) }
        if ($PROFILE.CurrentUserCurrentHost) { $paths.Add($PROFILE.CurrentUserCurrentHost) }
    }
    $pwshDir = Join-Path $env:USERPROFILE 'Documents\PowerShell'
    $paths.Add((Join-Path $pwshDir 'Microsoft.PowerShell_profile.ps1'))
    $paths.Add((Join-Path $pwshDir 'profile.ps1'))

    return ($paths | Select-Object -Unique)
}

$agyExe = Join-Path $AgyBinDirectory 'agy.exe'
$agyRealExe = Join-Path $AgyBinDirectory 'agy-real.exe'
$takeoverCmd = Join-Path $AgyBinDirectory 'agy.cmd'
$shimCmd = Join-Path $AgyBinDirectory 'agy-proxy.cmd'
$shimPs1 = Join-Path $AgyBinDirectory 'agy-proxy.ps1'
$statePath = "$ConfigPath.agy-proxy-state.json"

$beginMarker = '# ANTIGRAVITY_PROXY_PATCH_BEGIN'
$endMarker   = '# ANTIGRAVITY_PROXY_PATCH_END'
$profilePattern = '(?ms)^[ \t]*# ANTIGRAVITY_PROXY_PATCH_BEGIN.*?^[ \t]*# ANTIGRAVITY_PROXY_PATCH_END\r?\n?'

# 1. 基础路径及运行状态检测
$running = Get-Process -Name 'agy', 'agy-node', 'agy-real' -ErrorAction SilentlyContinue
if ($running) {
    $names = ($running | Select-Object -ExpandProperty ProcessName -Unique) -join '、'
    if ($Check) {
        Write-Status "检测到正在运行的 CLI 进程：$names (检查模式未做任何修改)"
    } else {
        Write-WarnStatus "检测到正在运行的 CLI 进程：$names。建议先退出相关进程再应用修改。"
    }
}

# 自动端口诊断与推荐
$portAccessible = Test-ProxyReachability $ProxyUrl
if (-not $portAccessible) {
    $detectedProxy = Detect-ActiveProxyPort
    if ($detectedProxy) {
        Write-Status "提示：检测到本机 $detectedProxy 正在监听代理服务。"
        if ($PSBoundParameters.ContainsKey('ProxyUrl')) {
            Write-WarnStatus "你指定的代理地址 $ProxyUrl 目前未连通，可考虑更换为 $detectedProxy。"
        } else {
            Write-Status "已自动选用检测到的活动代理：$detectedProxy"
            $ProxyUrl = $detectedProxy
            $portAccessible = $true
        }
    }
}

$exeFound = (Test-Path -LiteralPath $agyExe) -or (Test-Path -LiteralPath $agyRealExe)
$isTakeoverActive = (Test-Path -LiteralPath $agyRealExe) -and (Test-Path -LiteralPath $takeoverCmd)

# 2. 检查模式 (-Check)
if ($Check) {
    Write-Status "=== Antigravity CLI 代理状态诊断 ==="
    $exeStatus = if (Test-Path -LiteralPath $agyRealExe) {
        "$agyRealExe (已由 agy.cmd 接管)"
    } elseif (Test-Path -LiteralPath $agyExe) {
        "$agyExe (原生二进制)"
    } else {
        '未找到 [请确认是否安装]'
    }
    Write-Status "CLI 路径：$exeStatus"
    Write-Status "目标代理：$ProxyUrl"
    $portStatus = if ($portAccessible) { '正常 [监听中]' } else { '未连通 [代理客户端可能未启动或端口不匹配]' }
    Write-Status "代理端口连通性：$portStatus"

    if (Test-Path -LiteralPath $ConfigPath) {
        try {
            $currentConfig = [System.IO.File]::ReadAllText($ConfigPath) | ConvertFrom-Json
            $currentProxyUrl = $currentConfig.proxyServerURL
            if ($currentProxyUrl) {
                Write-Status "配置文件代理 (settings.json)：$currentProxyUrl"
            } else {
                Write-Status "配置文件代理 (settings.json)：未配置 proxyServerURL"
            }
            if ($currentConfig.modelProvider) {
                Write-WarnStatus "当前 modelProvider 设置为 $($currentConfig.modelProvider)（若未设置对应 API KEY 会导致无法打开，建议移除以使用 Google 账号官方登录）"
            } else {
                Write-Status "认证模式：Google 账号默认后端 (Default Backend)"
            }
        } catch {
            Write-WarnStatus "配置文件无法正常解析为 JSON：$ConfigPath"
        }
    } else {
        Write-Status "配置文件代理 (settings.json)：文件不存在"
    }

    $shimCmdStatus = if (Test-Path -LiteralPath $shimCmd) { '已就绪' } else { '未安装' }
    $shimPs1Status = if (Test-Path -LiteralPath $shimPs1) { '已就绪' } else { '未安装' }
    $takeoverStatus = if ($isTakeoverActive) { '已激活 (直接执行 agy 自动启用代理)' } else { '未激活' }

    Write-Status "专用垫片 (agy-proxy.cmd)：$shimCmdStatus"
    Write-Status "PowerShell 垫片 (agy-proxy.ps1)：$shimPs1Status"
    Write-Status "全终端 agy 接管 (agy.cmd)：$takeoverStatus"
    Write-Status "CLI 自动更新策略：启动器默认使用 AGY_CLI_DISABLE_AUTO_UPDATE=true，显式设为 false 可恢复后台自动更新"

    $profilePaths = Get-RelevantProfilePaths
    $hookFound = $false
    foreach ($p in $profilePaths) {
        if (Test-Path -LiteralPath $p) {
            $text = [System.IO.File]::ReadAllText($p)
            if ($text -match [regex]::Escape($beginMarker)) {
                $hookFound = $true
                Write-Status "PowerShell Profile 钩子：已安装于 $p"
            }
        }
    }
    if (-not $hookFound) {
        Write-Status "PowerShell Profile 钩子：未安装"
    }

    exit 0
}

# 3. 卸载/还原模式 (-Uninstall)
if ($Uninstall) {
    Write-Status "=== 正在还原 Antigravity CLI 代理配置 ==="

    # 3.1 只还原安装器修改过的配置字段，不覆盖安装后用户手工修改的值。
    # 旧版安装没有记录原值：此时绝不能猜测原配置或直接删除字段。
    $restorePending = $false
    if (-not (Test-Path -LiteralPath $statePath)) {
        $restorePending = $true
        Write-WarnStatus "未找到安装前配置记录：$statePath。为避免删除原有设置，未修改 settings.json。旧版备份可手工检查：$ConfigPath.bak-proxy-*"
    } else {
        try {
            $state = [System.IO.File]::ReadAllText($statePath) | ConvertFrom-Json
            if ($state.version -ne 1 -or
                $state.configPath -ne [System.IO.Path]::GetFullPath($ConfigPath) -or
                $null -eq $state.originalProxy -or
                $null -eq $state.originalModelProvider -or
                $null -eq $state.lastAppliedProxyUrl) {
                throw '安装前配置记录不完整或版本不受支持'
            }

            if (Test-Path -LiteralPath $ConfigPath) {
                $config = [System.IO.File]::ReadAllText($ConfigPath) | ConvertFrom-Json
                if ($null -eq $config -or $config -isnot [pscustomobject]) {
                    throw 'settings.json 不是有效的 JSON 对象'
                }
                $modified = $false
                $currentProxy = $config.PSObject.Properties['proxyServerURL']
                if ($null -ne $currentProxy) {
                    if ($currentProxy.Value -ceq $state.lastAppliedProxyUrl) {
                        if ($state.originalProxy.existed) {
                            Add-OrReplaceProperty $config 'proxyServerURL' $state.originalProxy.value
                        } else {
                            Remove-PropertyIfExists $config 'proxyServerURL'
                        }
                        $modified = $true
                    } elseif ($state.originalProxy.existed -and $currentProxy.Value -ceq $state.originalProxy.value) {
                        Write-Status 'proxyServerURL 已与首次安装前一致，无需修改。'
                    } else {
                        Write-WarnStatus '检测到 proxyServerURL 在安装后被修改，已保留用户当前值。'
                        $restorePending = $true
                    }
                } elseif ($state.originalProxy.existed) {
                    Write-WarnStatus 'proxyServerURL 已被手工移除，未擅自重新添加旧值。'
                    $restorePending = $true
                }

                if ($state.modelProviderRemoved -and $state.originalModelProvider.existed) {
                    if ($null -eq $config.PSObject.Properties['modelProvider']) {
                        Add-OrReplaceProperty $config 'modelProvider' $state.originalModelProvider.value
                        $modified = $true
                    } elseif (($config.modelProvider | ConvertTo-Json -Depth 30 -Compress) -ceq
                              ($state.originalModelProvider.value | ConvertTo-Json -Depth 30 -Compress)) {
                        Write-Status 'modelProvider 已与首次安装前一致，无需修改。'
                    } else {
                        Write-WarnStatus 'modelProvider 已重新配置，已保留用户当前值。'
                        $restorePending = $true
                    }
                }

                if ($modified) {
                    Backup-File $ConfigPath
                    if (-not $state.configExisted -and ($config | ConvertTo-Json -Depth 20 -Compress).Trim() -eq '{}') {
                        Remove-Item -LiteralPath $ConfigPath -Force -ErrorAction Stop
                        Write-Status '已移除安装器新建的空 settings.json'
                    } else {
                        Write-Utf8NoBom $ConfigPath (($config | ConvertTo-Json -Depth 20) + [Environment]::NewLine)
                        Write-Status '已恢复安装前的代理及认证配置，保留其他设置'
                    }
                }
            } elseif ($state.configExisted) {
                Write-WarnStatus '原 settings.json 已不存在，无法自动还原；保留安装记录。'
                $restorePending = $true
            }

            if (-not $restorePending) {
                Remove-Item -LiteralPath $statePath -Force -ErrorAction Stop
                Write-Status '已清理安装前配置记录'
            } else {
                Write-WarnStatus "部分配置未还原，记录仍保留在 $statePath，可手工核对后再卸载。"
            }
        } catch {
            $restorePending = $true
            Write-WarnStatus "无法安全恢复 settings.json：$_。保留安装记录及现有配置，请手工检查备份。"
        }
    }

    # 3.2 还原二进制接管
    $managedTakeover = Test-ManagedWrapper $takeoverCmd
    if ($managedTakeover) {
        Remove-Item -LiteralPath $takeoverCmd -Force -ErrorAction Stop
        Write-Status "已移除接管启动器：$takeoverCmd"
        if (Test-Path -LiteralPath $agyRealExe) {
            if (Test-Path -LiteralPath $agyExe) {
                Write-WarnStatus "同时存在 agy.exe 与 agy-real.exe，保留两个文件，避免覆盖原始程序。"
            } else {
                Move-Item -LiteralPath $agyRealExe -Destination $agyExe -ErrorAction Stop
                Write-Status "已还原二进制名称：$agyRealExe -> $agyExe"
            }
        }
    } elseif (Test-Path -LiteralPath $takeoverCmd) {
        Write-WarnStatus "agy.cmd 不是本安装器生成的文件，已保留：$takeoverCmd"
    } elseif (Test-Path -LiteralPath $agyRealExe) {
        Write-WarnStatus "找到 agy-real.exe 但没有受管接管启动器；无法确认来源，未改名。"
    }

    # 3.3 移除垫片
    foreach ($shim in @($shimCmd, $shimPs1)) {
        if (Test-ManagedWrapper $shim) {
            Remove-Item -LiteralPath $shim -Force -ErrorAction Stop
            Write-Status "已移除安装器生成的垫片：$shim"
        } elseif (Test-Path -LiteralPath $shim) {
            Write-WarnStatus "文件不是本安装器生成的，已保留：$shim"
        }
    }

    # 3.4 清理 PowerShell Profile 钩子（-NoProfileHook 时跳过）
    if (-not $NoProfileHook) {
        $profilePaths = Get-RelevantProfilePaths
        foreach ($p in $profilePaths) {
            if (Test-Path -LiteralPath $p) {
                $text = [System.IO.File]::ReadAllText($p)
                if ($text -match [regex]::Escape($beginMarker)) {
                    Backup-File $p
                    $newText = [regex]::Replace($text, $profilePattern, '')
                    Write-Utf8NoBom $p $newText
                    Write-Status "已从 Profile 移除钩子：$p"
                }
            }
        }
    }

    if ($restorePending) {
        Write-WarnStatus "启动器卸载流程已结束，但部分配置未能自动恢复；请检查上述警告。"
        exit 1
    }
    Write-Status "卸载与还原完成。"
    exit 0
}

# 4. 实际安装 / 修复流程
Write-Status "=== 正在应用 Antigravity CLI 代理补丁 ==="
Write-Status "目标代理地址：$ProxyUrl"

if (-not $portAccessible) {
    Write-WarnStatus "目标代理地址 $ProxyUrl 目前无法连接！请确保代理客户端（如 Clash/V2Ray/Sing-box 等）已开启且监听对应端口。"
}

# 安装前检查路径所有权，不能覆盖用户自有启动器。
if (-not $NoShim) {
    foreach ($shim in @($shimCmd, $shimPs1)) {
        if ((Test-Path -LiteralPath $shim) -and -not (Test-ManagedWrapper $shim)) {
            throw "发现非本安装器生成的启动器，拒绝覆盖：$shim"
        }
    }
}
if ($TakeoverAgy -and (Test-Path -LiteralPath $takeoverCmd) -and -not (Test-ManagedWrapper $takeoverCmd)) {
    throw "发现非本安装器生成的 agy.cmd，拒绝覆盖：$takeoverCmd"
}

# 4.1 更新 settings.json，并为卸载保存首次安装前的字段状态
$configExisted = Test-Path -LiteralPath $ConfigPath
if ($configExisted) {
    Backup-File $ConfigPath
    try {
        $config = [System.IO.File]::ReadAllText($ConfigPath) | ConvertFrom-Json
        if ($null -eq $config -or $config -isnot [pscustomobject]) {
            throw 'settings.json 不是有效的 JSON 对象'
        }
    } catch {
        throw "原配置文件无法正常解析；为避免覆盖用户设置，已停止安装：$_"
    }
} else {
    $config = [pscustomobject]@{}
}

if (Test-Path -LiteralPath $statePath) {
    try {
        $state = [System.IO.File]::ReadAllText($statePath) | ConvertFrom-Json
        if ($state.version -ne 1 -or
            $state.configPath -ne [System.IO.Path]::GetFullPath($ConfigPath) -or
            $null -eq $state.originalProxy -or
            $null -eq $state.originalModelProvider) {
            throw '安装记录不完整或版本不受支持'
        }
    } catch {
        throw "无法读取之前的安装记录 $statePath；为避免覆盖最初的备份，请先手工检查：$_"
    }
} else {
    $originalProxyProperty = $config.PSObject.Properties['proxyServerURL']
    $originalModelProviderProperty = $config.PSObject.Properties['modelProvider']
    $state = [pscustomobject]@{
        version = 1
        configPath = [System.IO.Path]::GetFullPath($ConfigPath)
        configExisted = [bool]$configExisted
        originalProxy = [pscustomobject]@{
            existed = ($null -ne $originalProxyProperty)
            value = $(if ($null -ne $originalProxyProperty) { $originalProxyProperty.Value } else { $null })
        }
        originalModelProvider = [pscustomobject]@{
            existed = ($null -ne $originalModelProviderProperty)
            value = $(if ($null -ne $originalModelProviderProperty) { $originalModelProviderProperty.Value } else { $null })
        }
        modelProviderRemoved = $false
        lastAppliedProxyUrl = $null
    }
}

# 重复安装时只更新最后一次注入值，保留首次安装之前的原始配置。
$state.lastAppliedProxyUrl = $ProxyUrl
Add-OrReplaceProperty $config 'proxyServerURL' $ProxyUrl

if ($null -ne $config.modelProvider -and -not $env:GEMINI_API_KEY) {
    Remove-PropertyIfExists $config 'modelProvider'
    $state.modelProviderRemoved = $true
    Write-Status "已自动移除 modelProvider，配置为支持 Google 账号官方登录"
}

# 先写恢复记录再写目标配置，确保任何一次实际修改都存在恢复依据。
Save-InstallState $statePath $state
Write-Utf8NoBom $ConfigPath (($config | ConvertTo-Json -Depth 20) + [Environment]::NewLine)
Write-Status "已安全写入 settings.json (UTF-8 无 BOM)，并记录卸载所需的原始配置"

# 4.2 安装环境隔离 Shim 启动器 (agy-proxy.cmd / agy-proxy.ps1)
if (-not $NoShim) {
    if (-not (Test-Path -LiteralPath $AgyBinDirectory)) {
        New-Item -ItemType Directory -Path $AgyBinDirectory -Force | Out-Null
    }

    $cmdContent = @"
